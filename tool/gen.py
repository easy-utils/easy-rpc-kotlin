#!/usr/bin/env python3
# protoc-gen-easyrpc-kotlin: emit <file>_easyrpc.kt strong-typed client.
import sys
from google.protobuf.compiler import plugin_pb2 as plugin

def resolve(f):
    out=[]
    pkg=f.package or ''
    for svc in f.service:
        for m in svc.method:
            pp=rest_path(m) or f'/{pkg}.{svc.name}/{m.name}'
            out.append((svc.name, m.name or '', pp, m.server_streaming, m.input_type.split('.')[-1], m.output_type.split('.')[-1]))
    return out



def rest_path(m):
    opts=m.options
    if not opts: return None
    try:
        raw=opts.SerializeToString(); pos=0
        while pos < len(raw):
            tag,pos=readvar(raw,pos); field=tag>>3; wt=tag&7
            if wt==2:
                ln,pos=readvar(raw,pos); val=raw[pos:pos+ln]; pos+=ln
                if field==72295728:
                    p=parse_rule(val)
                    if p: return p
            elif wt==0: _,pos=readvar(raw,pos)
            elif wt==5: pos+=4
            elif wt==1: pos+=8
    except Exception: return None
    return None
def readvar(b,i):
    v=0;s=0
    while True:
        x=b[i] if i<len(b) else 0; i+=1; v|=(x&0x7f)<<s;s+=7
        if not x&0x80: break
    return v,i
def parse_rule(d):
    i=0
    while i<len(d):
        tag,i=readvar(d,i); field=tag>>3; wt=tag&7
        if wt==2:
            ln,i=readvar(d,i); val=d[i:i+ln].decode(); i+=ln
            if field in (2,4,3,6): return val
        elif wt==0: _,i=readvar(d,i)
        elif wt==5: i+=4
        elif wt==1: i+=8
    return None
def main():
    data=sys.stdin.buffer.read()
    req=plugin.CodeGeneratorRequest.FromString(data)
    files=[]
    for f in req.proto_file:
        if f.name not in req.file_to_generate: continue
        ms=resolve(f)
        if not ms: continue
        base=f.name[:-6]
        L=['// Code generated by protoc-gen-easyrpc-kotlin. DO NOT EDIT.','package easyrpc','','import easyrpc.*','import com.easyrpc.conformance.v1.*','import kotlinx.coroutines.flow.Flow','import kotlinx.coroutines.flow.flow','']
        L.append('class ConformanceServiceClient(private val t: Transport) {')
        for (svc,name,path,ss,it,ot) in ms:
            if ss:
                L.append(f'  fun {camel(name)}(req: {it}): Flow<{ot}> = flow {{')
                L.append(f'    val st = t.openStream(Request(url = "{path}", body = req.toByteArray()))')
                L.append(f'    while (true) {{ val p = st.recv() ?: break; emit({ot}.parseFrom(p)) }}')
                L.append('  }')
            else:
                L.append(f'  suspend fun {camel(name)}(req: {it}): {ot} {{')
                L.append(f'    val res = t.send(Request(url = "{path}", body = req.toByteArray()))')
                L.append(f'    res.error?.let{{ throw it }}')
                L.append(f'    return {ot}.parseFrom(res.body)')
                L.append('  }')
            L.append('')
        L.append('}')
        content='\n'.join(L)
        files.append(plugin.CodeGeneratorResponse.File(name=base+'_easyrpc.kt', content=content))
    resp=plugin.CodeGeneratorResponse(file=files)
    sys.stdout.buffer.write(resp.SerializeToString())

def camel(s): return s[:1].lower()+s[1:]
if __name__=='__main__': main()
